#!/usr/bin/env python3
"""Generate components/webgl/broker_wire.rs from WebGLCommand in canvas traits."""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WEBGL_RS = ROOT / "packages/lotus-core/servo/components/shared/canvas/webgl.rs"
OUT = ROOT / "packages/lotus-core/servo/components/webgl/broker_wire.rs"


def parse_variants(body: str) -> list[tuple[str, str, list]]:
    variants: list[str] = []
    buf: list[str] = []
    brace = paren = 0
    for line in body.split("\n"):
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        if "//" in s:
            s = s[: s.index("//")].rstrip()
        buf.append(s)
        brace += s.count("{") - s.count("}")
        paren += s.count("(") - s.count(")")
        joined = " ".join(buf)
        if brace == 0 and paren == 0 and joined.endswith(","):
            variants.append(joined[:-1].strip())
            buf = []
    if buf:
        variants.append(" ".join(buf).strip().rstrip(","))

    parsed = []
    for v in variants:
        v = " ".join(v.split())
        if "{" in v:
            name = v.split("{", 1)[0].strip()
            fields_s = v[v.index("{") + 1 : v.rindex("}")].strip()
            fields = split_top(fields_s)
            named = []
            for f in fields:
                fn, ft = f.split(":", 1)
                named.append((fn.strip(), ft.strip().rstrip(",")))
            parsed.append(("struct", name, named))
        elif "(" in v:
            name = v.split("(", 1)[0].strip()
            args = split_top(v[v.index("(") + 1 : v.rindex(")")].strip())
            parsed.append(("tuple", name, args))
        else:
            parsed.append(("unit", v.strip(), []))
    return parsed


def split_top(s: str) -> list[str]:
    args: list[str] = []
    depth = 0
    cur = ""
    for ch in s:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == "," and depth == 0:
            if cur.strip():
                args.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        args.append(cur.strip())
    return args


def wire_type(t: str) -> str:
    t = t.strip()
    if t.startswith("GenericSender<"):
        return "u64"
    if t.startswith("GenericReceiver<"):
        return "Vec<u8>"
    if "TruncatedDebug<GenericSharedMemory>" in t:
        return "Vec<u8>"
    if t == "GenericSharedMemory":
        return "Vec<u8>"
    return t


def sender_inner(a: str) -> str:
    return a[len("GenericSender<") : -1]


def main() -> int:
    text = WEBGL_RS.read_text()
    m = re.search(r"pub enum WebGLCommand \{(.*?)\n\}", text, re.S)
    if not m:
        print("WebGLCommand not found", file=sys.stderr)
        return 1
    parsed = parse_variants(m.group(1))

    out: list[str] = []
    out += [
        "/* AUTO-GENERATED by scripts/gen-webgl-broker-wire.py — do not edit by hand. */",
        "/* This Source Code Form is subject to the terms of the Mozilla Public",
        " * License, v. 2.0. If a copy of the MPL was not distributed with this",
        " * file, You can obtain one at https://mozilla.org/MPL/2.0/. */",
        "",
        "use euclid::default::{Rect, Size2D};",
        "use pixels::{PixelFormat, SnapshotAlphaMode};",
        "use serde::{Deserialize, Serialize};",
        "use servo_base::generic_channel::{GenericReceiver, GenericSender, GenericSharedMemory};",
        "use servo_canvas_traits::webgl::{",
        "    webgl_channel, AlphaTreatment, GLContextAttributes, InternalFormatIntVec, ParameterBool,",
        "    ParameterBool4, ParameterFloat, ParameterFloat2, ParameterFloat4, ParameterInt,",
        "    ParameterInt2, ParameterInt4, ParameterUInt, ProgramLinkInfo, TexDataType, TexFormat,",
        "    TexParameterBool, TexParameterFloat, TexParameterInt, TruncatedDebug, WebGLBufferId,",
        "    WebGLCommand, WebGLError, WebGLFramebufferBindingRequest, WebGLFramebufferId,",
        "    WebGLProgramId, WebGLQueryId, WebGLRenderbufferId, WebGLSamplerId, WebGLShaderId,",
        "    WebGLSyncId, WebGLTextureId, WebGLVertexArrayId, YAxisTreatment,",
        "};",
        "",
        "/// Pending reply delivery on the engine side after a wire round-trip.",
        "pub type PendingReply = Box<dyn FnOnce(Option<Vec<u8>>) + Send>;",
        "",
        "#[derive(Debug, Serialize, Deserialize)]",
        "pub enum WireWebGLCommand {",
    ]
    for kind, name, args in parsed:
        if kind == "unit":
            out.append(f"    {name},")
        elif kind == "tuple":
            wargs = ", ".join(wire_type(a) for a in args)
            out.append(f"    {name}({wargs}),")
        else:
            fields = ", ".join(f"{fn}: {wire_type(ft)}" for fn, ft in args)
            out.append(f"    {name} {{ {fields} }},")
    out.append("}")
    out.append("")

    # strip
    out += [
        "pub fn strip_webgl_command(",
        "    cmd: WebGLCommand,",
        "    next_corr: &mut u64,",
        ") -> (WireWebGLCommand, Option<(u64, PendingReply)>) {",
        "    match cmd {",
    ]
    for kind, name, args in parsed:
        if kind == "unit":
            out.append(f"        WebGLCommand::{name} => (WireWebGLCommand::{name}, None),")
            continue
        if kind == "struct":
            binds = ", ".join(fn for fn, _ in args)
            out.append(f"        WebGLCommand::{name} {{ {binds} }} => {{")
            wire_fields = []
            for fn, ft in args:
                if "TruncatedDebug" in ft or (
                    "GenericSharedMemory" in ft and "GenericSender" not in ft
                ):
                    out.append(f"            let {fn}_bytes = {fn}.as_ref().to_vec();")
                    wire_fields.append(f"{fn}: {fn}_bytes")
                else:
                    wire_fields.append(fn)
            out.append(
                f"            (WireWebGLCommand::{name} {{ {', '.join(wire_fields)} }}, None)"
            )
            out.append("        },")
            continue

        binders = [f"a{i}" for i in range(len(args))]
        pat = ", ".join(binders)
        needs_special = any(
            x in a
            for a in args
            for x in ("GenericSender", "GenericReceiver", "GenericSharedMemory", "TruncatedDebug")
        )
        if not needs_special:
            out.append(
                f"        WebGLCommand::{name}({pat}) => (WireWebGLCommand::{name}({pat}), None),"
            )
            continue

        out.append(f"        WebGLCommand::{name}({pat}) => {{")
        wire_args: list[str] = []
        pending_code = "None"
        for i, a in enumerate(args):
            if a.startswith("GenericSender<"):
                inner = sender_inner(a)
                out.append(
                    "            let corr = { *next_corr = next_corr.wrapping_add(1); *next_corr };"
                )
                out.append(f"            let sender = a{i};")
                # SharedMemory replies need a wire-friendly payload.
                if inner == "GenericSharedMemory":
                    out.append(
                        "            let pending: PendingReply = Box::new(move |bytes: Option<Vec<u8>>| {"
                    )
                    out.append("                if let Some(b) = bytes {")
                    out.append(
                        "                    let _ = sender.send(GenericSharedMemory::from_bytes(&b));"
                    )
                    out.append("                }")
                    out.append("            });")
                elif inner.startswith("(GenericSharedMemory,"):
                    out.append(
                        "            let pending: PendingReply = Box::new(move |bytes: Option<Vec<u8>>| {"
                    )
                    out.append(
                        "                if let Some(b) = bytes {"
                    )
                    out.append(
                        "                    if let Ok((data, alpha)) = rmp_serde::from_slice::<(Vec<u8>, SnapshotAlphaMode)>(&b) {"
                    )
                    out.append(
                        "                        let _ = sender.send((GenericSharedMemory::from_bytes(&data), alpha));"
                    )
                    out.append("                    }")
                    out.append("                }")
                    out.append("            });")
                else:
                    out.append(
                        "            let pending: PendingReply = Box::new(move |bytes: Option<Vec<u8>>| {"
                    )
                    out.append("                match bytes {")
                    out.append("                    Some(b) => {")
                    out.append(
                        f"                        if let Ok(v) = rmp_serde::from_slice::<{inner}>(&b) {{"
                    )
                    out.append("                            let _ = sender.send(v);")
                    out.append("                        }")
                    out.append("                    },")
                    if "Option<" in inner:
                        out.append(
                            "                    None => { let _ = sender.send(None); },"
                        )
                    elif inner == "WebGLError":
                        out.append(
                            "                    None => { let _ = sender.send(WebGLError::ContextLost); },"
                        )
                    elif "Result<" in inner and "WebGLError" in inner:
                        out.append(
                            "                    None => { let _ = sender.send(Err(WebGLError::ContextLost)); },"
                        )
                    elif inner == "()":
                        out.append(
                            "                    None => { let _ = sender.send(()); },"
                        )
                    else:
                        out.append("                    None => {},")
                    out.append("                }")
                    out.append("            });")
                wire_args.append("corr")
                pending_code = "Some((corr, pending))"
            elif a.startswith("GenericReceiver<" ):
                out.append(
                    f"            let bytes = a{i}.recv().map(|m| m.as_ref().to_vec()).unwrap_or_default();"
                )
                wire_args.append("bytes")
            elif "TruncatedDebug" in a:
                out.append(f"            let bytes = a{i}.as_ref().to_vec();")
                wire_args.append("bytes")
            elif a == "GenericSharedMemory":
                out.append(f"            let bytes = a{i}.as_ref().to_vec();")
                wire_args.append("bytes")
            else:
                wire_args.append(f"a{i}")
        out.append(
            f"            (WireWebGLCommand::{name}({', '.join(wire_args)}), {pending_code})"
        )
        out.append("        },")
    out += ["    }", "}", ""]

    # rehydrate
    out += [
        "pub type ReplyWaiter = Box<dyn FnOnce() -> Option<Vec<u8>> + Send>;",
        "",
        "pub fn rehydrate_webgl_command(",
        "    wire: WireWebGLCommand,",
        ") -> (WebGLCommand, Option<(u64, ReplyWaiter)>) {",
        "    match wire {",
    ]
    for kind, name, args in parsed:
        if kind == "unit":
            out.append(f"        WireWebGLCommand::{name} => (WebGLCommand::{name}, None),")
            continue
        if kind == "struct":
            binds = ", ".join(fn for fn, _ in args)
            rebuild = []
            for fn, ft in args:
                if "TruncatedDebug" in ft:
                    rebuild.append(
                        f"{fn}: TruncatedDebug::from(GenericSharedMemory::from_bytes(&{fn}))"
                    )
                elif "GenericSharedMemory" in ft:
                    rebuild.append(f"{fn}: GenericSharedMemory::from_bytes(&{fn})")
                else:
                    rebuild.append(fn)
            out.append(
                f"        WireWebGLCommand::{name} {{ {binds} }} => "
                f"(WebGLCommand::{name} {{ {', '.join(rebuild)} }}, None),"
            )
            continue

        binders = [f"a{i}" for i in range(len(args))]
        pat = ", ".join(binders)
        needs_special = any(
            x in a
            for a in args
            for x in ("GenericSender", "GenericReceiver", "GenericSharedMemory", "TruncatedDebug")
        )
        if not needs_special:
            out.append(
                f"        WireWebGLCommand::{name}({pat}) => (WebGLCommand::{name}({pat}), None),"
            )
            continue

        out.append(f"        WireWebGLCommand::{name}({pat}) => {{")
        cmd_args: list[str] = []
        wait_code = "None"
        for i, a in enumerate(args):
            if a.startswith("GenericSender<" ):
                inner = sender_inner(a)
                out.append(f"            let corr = a{i};")
                if inner == "GenericSharedMemory":
                    out.append(
                        "            let (tx, rx) = webgl_channel::<GenericSharedMemory>().expect(\"ch\");"
                    )
                    out.append(
                        "            let wait: ReplyWaiter = Box::new(move || {"
                    )
                    out.append(
                        "                rx.recv().ok().map(|m| m.as_ref().to_vec())"
                    )
                    out.append("            });")
                elif inner.startswith("(GenericSharedMemory,"):
                    out.append(
                        "            let (tx, rx) = webgl_channel::<(GenericSharedMemory, SnapshotAlphaMode)>().expect(\"ch\");"
                    )
                    out.append(
                        "            let wait: ReplyWaiter = Box::new(move || {"
                    )
                    out.append("                rx.recv().ok().and_then(|(m, alpha)| {")
                    out.append(
                        "                    rmp_serde::to_vec(&(m.as_ref().to_vec(), alpha)).ok()"
                    )
                    out.append("                })")
                    out.append("            });")
                else:
                    out.append(
                        f"            let (tx, rx) = webgl_channel::<{inner}>().expect(\"ch\");"
                    )
                    out.append(
                        "            let wait: ReplyWaiter = Box::new(move || {"
                    )
                    out.append(
                        "                rx.recv().ok().and_then(|v| rmp_serde::to_vec(&v).ok())"
                    )
                    out.append("            });")
                cmd_args.append("tx")
                wait_code = "Some((corr, wait))"
            elif a.startswith("GenericReceiver<" ):
                out.append(
                    "            let (tx, rx) = webgl_channel::<GenericSharedMemory>().expect(\"ch\");"
                )
                out.append(
                    f"            let _ = tx.send(GenericSharedMemory::from_bytes(&a{i}));"
                )
                cmd_args.append("rx")
            elif "TruncatedDebug" in a:
                out.append(
                    f"            let shm = TruncatedDebug::from(GenericSharedMemory::from_bytes(&a{i}));"
                )
                cmd_args.append("shm")
            elif a == "GenericSharedMemory":
                cmd_args.append(f"GenericSharedMemory::from_bytes(&a{i})")
            else:
                cmd_args.append(f"a{i}")
        out.append(
            f"            (WebGLCommand::{name}({', '.join(cmd_args)}), {wait_code})"
        )
        out.append("        },")
    out += ["    }", "}", ""]

    OUT.write_text("\n".join(out) + "\n")
    print(f"Wrote {OUT} ({OUT.stat().st_size} bytes, {len(parsed)} variants)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
